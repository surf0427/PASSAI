// ── buildTutorUserPrompt（実装 STEP4） ───────────────────────────
//
// Anthropic messages.create の messages[0].content に渡す user prompt を組み立てる純粋関数。
//
// 役割:
//   - context builder（lib/contextBuilders/tutor/buildTutorPromptContext）の出力 contextString と、
//     受験生の最新メッセージ userMessage を結合し、1 本の文字列にする
//   - 動的データはここに集約し、TUTOR_SYSTEM_PROMPT には絶対に混ぜない
//     （SYSTEM の byte-identical / cache_control: 'ephemeral' を守るため）
//
// 出力フォーマット:
//   - contextString に内容がある場合:
//       {contextString}
//       <空行>
//       【受験生からの最新メッセージ】
//       {userMessage}
//   - contextString が空（trim 後）の場合:
//       【受験生からの最新メッセージ】
//       {userMessage}
//
// 仕様:
//   - 両入力に trim を適用する
//   - userMessage が空でも「【受験生からの最新メッセージ】」section 自体は出す
//   - userMessage 長さ validation は本関数では行わない（route 側責務）
//   - throw しない
//
// 純粋関数: fetch / localStorage / Supabase / Date / Math.random / console 一切なし。

export function buildTutorUserPrompt(input: {
  contextString: string;
  userMessage: string;
}): string {
  const context = input.contextString.trim();
  const message = input.userMessage.trim();

  const messageSection = ['【受験生からの最新メッセージ】', message].join('\n');

  if (context === '') {
    return messageSection;
  }
  return [context, messageSection].join('\n\n');
}

// ── buildTutorStudentContextSection（STEP-TUTOR-STUDENT-CONTEXT） ──
//
// PASSAI 内の保存データから要約した studentContext を、SYSTEM PROMPT に追加する
// 「【PASSAI内の生徒情報】」section の string に整形する純粋関数。
//
// 設計意図:
//   - TUTOR_SYSTEM_PROMPT（byte-identical / cache_control: 'ephemeral'）は一切変更しない。
//     本 section は route 側で system の **2 つ目の block**（cache 対象外）として渡すことで、
//     静的 prompt の cache hit を保ったまま、ユーザーごとに変わる動的情報を注入する。
//   - studentContext が空（trim 後）なら空文字を返す。route 側は空なら block を足さない。
//   - section 本体には「参考情報の扱い方ルール」を併記する。これは AI が studentContext を
//     どう扱うべきかの instruction であり、studentContext 本体（builder の出力）と分離する。
//
// 利用ルール（section 内に明記する instruction・v20 改訂で個別最適化を優先）:
//   - 受験・進路の話題では積極的に活用し、個別最適化された助言を行う
//   - ただし単なる復唱・列挙や毎回の引用は避け、背景知識として使う
//   - 雑談・受験外の話題では無理に参照しない
//   - 参考情報であり、ユーザーの現在の発言を最優先する（矛盾時は最新発言を信じる）
//   - 情報が古い可能性があるため断定しすぎない
//   - 「あなたのデータによると」と機械的に言いすぎない
//   - 個人情報を推測・補完しない / 未入力項目を責めない
//
// 純粋関数: fetch / localStorage / Supabase / Date / Math.random / console 一切なし。

export function buildTutorStudentContextSection(
  studentContext?: string | null,
): string {
  const context = (studentContext ?? '').trim();
  if (context === '') return '';

  return [
    '【PASSAI内の生徒情報】',
    context,
    '',
    'この生徒情報の扱い方:',
    '・受験・進路の話題では積極的に活用し、その生徒に合わせた個別最適化された助言を行ってください。',
    '・ただし単なる復唱・列挙や毎回の引用は避け、より良い助言のための背景知識として使ってください。',
    '・雑談・受験外の話題では無理に参照しないでください（利用頻度は低めに）。',
    '・これは参考情報です。ユーザーの現在の発言を常に最優先し、矛盾する場合は最新発言を信じてください。',
    '・情報が古い可能性があるため、断定しすぎないでください。',
    '・「あなたのデータによると」のように機械的に言いすぎないでください。',
    '・ここに無い個人情報を推測・補完しないでください。',
    '・「未入力」の項目を責めたり、入力を急かしたりしないでください。',
  ].join('\n');
}
