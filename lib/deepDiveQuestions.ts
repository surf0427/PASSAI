export function getSummaryForPhrase(phrase: string): DeepDiveSummaryData {
  const entry = SUMMARY_MAP[phrase] ?? DEFAULT_SUMMARY_ENTRY;
  const missing = ALL_ELEMENTS.filter(
    (el) => !entry.strengthenedElements.includes(el)
  );
  return {
    recommendedParagraph: entry.recommendedParagraph,
    strengthenedElements: entry.strengthenedElements,
    missingElements: missing,
    checklist: entry.checklist,
    caution: entry.caution,
  };
}
